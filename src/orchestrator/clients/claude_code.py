"""Generate and install Claude Code assets.

Three kinds of file are written into the user's global Claude Code directory:

* ``agents/*.md`` — one subagent per orchestrator agent, so `@orc-planner`
  works inside any project;
* ``commands/*.md`` — slash commands (`/orc-run`, `/orc-status`, …) that shell
  out to the same CLI a terminal user would type;
* ``skills/*/SKILL.md`` — the shared engineering skills, so Claude Code applies
  the same conventions even outside an orchestrated run.

Everything is derived from the registry and the skill library, so adding an
agent or a skill automatically extends what Claude Code sees.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

from orchestrator.agents.registry import AGENT_REGISTRY, PIPELINE
from orchestrator.skills.loader import load_skills

MANAGED_HEADER = "<!-- generated by mobile-eng-orchestrator; edits will be overwritten -->"


def claude_home() -> Path:
    return Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude")).expanduser()


@dataclass
class InstalledAsset:
    kind: str
    name: str
    path: Path


def _agent_markdown(name: str) -> str:
    spec = AGENT_REGISTRY[name]
    agent = spec.instantiate()
    tools = "Bash, Read, Grep, Glob" if not agent.mutates_repository else "Bash, Read, Grep, Glob, Edit, Write"
    return f"""---
name: orc-{name}
description: {agent.responsibility} Part of the engineering orchestrator pipeline (phase: {spec.phase}).
tools: {tools}
---

{MANAGED_HEADER}

You are the **{name}** agent of the engineering orchestrator.

**Responsibility:** {agent.responsibility}

**Consumes:** {spec.consumes}
**Produces:** {spec.produces}

## How to run this phase

This agent is a thin wrapper around the orchestrator CLI, which owns the state
machine, the approval gates and the audit log. Do not reimplement the phase by
hand — run it:

```bash
orc run <ISSUE-KEY> --stop-after {spec.phase}
```

Then read the artifact it produced:

```bash
orc show {spec.produces.lower()}.md 2>/dev/null || orc status
```

## Rules

- Never skip an approval gate. If the CLI stops and asks for approval, surface
  that to the developer and wait.
- Never commit, push or open a pull request outside the `delivery` phase.
- If the CLI reports an error, show it verbatim rather than working around it.
"""


def _command_markdown(name: str, description: str, body: str) -> str:
    return f"""---
description: {description}
---

{MANAGED_HEADER}

{body}
"""


COMMANDS: dict[str, tuple[str, str]] = {
    "orc-run": (
        "Run the full engineering orchestration workflow for a Jira ticket.",
        """Run the orchestrator for the ticket the user names.

```bash
orc run $ARGUMENTS
```

The workflow fetches the ticket, derives requirements, plans, waits for the
developer to approve the plan, implements, validates, reviews, and waits again
before committing or opening a PR.

Show the developer the plan when the run pauses, and do not approve on their
behalf.""",
    ),
    "orc-plan": (
        "Fetch a ticket and produce an implementation plan, stopping before any edits.",
        """```bash
orc run $ARGUMENTS --stop-after plan
orc show plan.md
```

Present the plan to the developer and ask whether to proceed with
`orc approve`.""",
    ),
    "orc-status": (
        "Show the state of orchestrator runs in this repository.",
        """```bash
orc status --all
```

Then, for the run the developer cares about:

```bash
orc status <RUN-ID>
```""",
    ),
    "orc-approve": (
        "Approve the gate the current run is waiting on and continue it.",
        """```bash
orc approve $ARGUMENTS
```

Confirm with the developer before running this — it is the human gate.""",
    ),
    "orc-validate": (
        "Re-run the platform's validation checks for the current run.",
        """```bash
orc validate
```

Report which checks passed, failed or were skipped, and why.""",
    ),
    "orc-inspect": (
        "Detect the platform and capabilities of the current repository.",
        """```bash
orc inspect
```

Summarise what the orchestrator detected and flag anything that would block a
run.""",
    ),
}


def _skill_dir_name(name: str) -> str:
    return f"orc-{name}"


def install_claude_code_assets(
    *, target: Path | None = None, dry_run: bool = False
) -> list[InstalledAsset]:
    """Write agents, commands and skills into the Claude Code config directory."""
    root = Path(target) if target else claude_home()
    installed: list[InstalledAsset] = []

    agents_dir = root / "agents"
    commands_dir = root / "commands"
    skills_dir = root / "skills"

    for name in (*PIPELINE, "platform-ios", "platform-android"):
        path = agents_dir / f"orc-{name}.md"
        installed.append(InstalledAsset("agent", f"orc-{name}", path))
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(_agent_markdown(name), encoding="utf-8")

    for command, (description, body) in COMMANDS.items():
        path = commands_dir / f"{command}.md"
        installed.append(InstalledAsset("command", f"/{command}", path))
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(_command_markdown(command, description, body), encoding="utf-8")

    for skill in load_skills():
        directory = skills_dir / _skill_dir_name(skill.name)
        path = directory / "SKILL.md"
        installed.append(InstalledAsset("skill", skill.name, path))
        if not dry_run:
            directory.mkdir(parents=True, exist_ok=True)
            applies = ", ".join(p.value for p in skill.applies_to) or "any"
            path.write_text(
                f"---\nname: orc-{skill.name}\n"
                f"description: {skill.description} (applies to: {applies})\n---\n\n"
                f"{MANAGED_HEADER}\n\n{skill.body.strip()}\n",
                encoding="utf-8",
            )

    return installed


def uninstall_claude_code_assets(*, target: Path | None = None) -> list[Path]:
    """Remove only the files this generator owns."""
    root = Path(target) if target else claude_home()
    removed: list[Path] = []
    for pattern in ("agents/orc-*.md", "commands/orc-*.md"):
        for path in root.glob(pattern):
            path.unlink()
            removed.append(path)
    for directory in (root / "skills").glob("orc-*"):
        skill_file = directory / "SKILL.md"
        if skill_file.exists():
            skill_file.unlink()
            removed.append(skill_file)
        if not any(directory.iterdir()):
            directory.rmdir()
    return removed
